const translations = { cs, en } as const;
export type TranslationKey = keyof typeof cs;

export function resolveLocale(): Locale {
  try {
    const saved = window.localStorage.getItem(localeStorageKey);
    if (saved === "cs" || saved === "en") return saved;
  } catch {
    // A blocked storage API must not prevent the app from starting.
  }
  return navigator.language.toLowerCase().startsWith("cs") ? "cs" : "en";
}

export function persistLocale(locale: Locale): void {
  try {
    window.localStorage.setItem(localeStorageKey, locale);
  } catch {
    // The selected locale still applies to the current reload when storage is blocked.
  }
}

export type CopyPlatform = "windows" | "linux";

export function createTranslator(locale: Locale, platform: CopyPlatform = "windows") {
  const overrides: Partial<Record<TranslationKey, string>> = platform === "linux" ? linuxOverrides[locale] : {};
  return (key: TranslationKey, values: Record<string, string | number> = {}): string =>
    Object.entries(values).reduce(
      (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
      overrides[key] ?? translations[locale][key],
    );
}

const SERVICE_ERROR_PATTERN = /^HOMEPROXY_SERVICE:([a-z_]+):([\s\S]*)$/;

