export function isServiceConflict(message: string): boolean {
  const code = SERVICE_ERROR_PATTERN.exec(message)?.[1];
  return code === "conflict" || code === "revision_required";
}

/** Localizes a `HOMEPROXY_SERVICE:<code>:<message>` failure from the Linux backend. */
export function translateServiceError(message: string, locale: Locale, platform: CopyPlatform): string | null {
  const match = SERVICE_ERROR_PATTERN.exec(message);
  if (!match) return null;
  const [, code, detail] = match;
  const t = createTranslator(locale, platform);
  const key = serviceErrorKeys[code];
  if (key) return t(key);
  if (code === "invalid_config") return t("serviceInvalidConfig", { message: translateBackendMessage(detail, locale) });
  return t("serviceGenericError", { code, message: detail });
}

